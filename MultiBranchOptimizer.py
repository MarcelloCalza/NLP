from init_prompts import apply_prompt
from tqdm import tqdm
import random
import re
import hashlib
from copy import deepcopy
from PromptObject import PromptObject


class MultiBranchOptimizer:
    """
    Optimizes prompts through iterative mutation and evaluation using multiple prompt
    modification strategies.

    This optimizer maintains a pool of high-performing prompts and progressively
    improves them through targeted mutations applied to individual prompt components:
    instructions, reasoning steps, examples, or complete prompt rewrites. Candidate
    prompts are evaluated on a task optmization dataset and ranked according to their
    performance.

    The optimization process uses failure analysis to identify common weaknesses in
    model predictions and guide future mutations. A top-k population strategy is used
    to preserve strong prompts while exploring new variations generated by a mutation
    model.
    """

    def __init__(
        self,
        model,
        evaluator,
        dataset,
        mutation_model=None,
        judge_model=None,
        branches=("instruction", "cot", "examples", "rewrite"),
        max_examples=200,
        k=5,
        patience=10,
        max_failures=10,
        n_reasons=3,
        optimizer_system=(
            "You are a helpful assistant. "
            "Return only what is requested. "
            "Do not explain your reasoning. "
            "Do not add labels, prefixes, suffixes, code blocks, "
            "or commentary. "
        ),
        seed=None,
    ):
        """
        Initializes the prompt optimization framework.

        Args:
            model: Model used for prompt evaluation.
            evaluator: Function used to evaluate prompt performance.
            dataset (list): Dataset used for prompt optimization.
            mutation_model (optional): Model used to generate prompt mutations.
            judge_model (optional): Model used for LLM-based judging.
            branches (tuple, optional): Mutation strategies for optimization.
            max_examples (int, optional): Number of examples evaluated per prompt.
            k (int, optional): Number of prompts retained in the optimization pool.
            patience (int, optional): Early stopping patience measured in generations.
            max_failures (int, optional):
                Number of failed examples used for failure analysis.
            n_reasons (int, optional):
                Max number of failure patterns detected by the failure analysis.
            optimizer_system (str, optional): System prompt used by the mutation model.
            seed (int, optional): Random seed for reproducibility.
        """
        self.model = model
        self.evaluator = evaluator
        self.dataset = dataset
        self.mutation_model = mutation_model or model
        self.judge_model = judge_model or None
        self.branches = branches
        self.max_examples = max_examples
        self.optimizer_system = optimizer_system
        self.seed = seed
        self.cache = {}
        self.pool = []
        self.k = k
        self.patience = patience
        self.mutation_log = []
        self.rng = random.Random(seed)
        self.output_constraints = dataset[0]["input"]
        self.optimizer_prompt_log = []
        self.max_failures = max_failures
        self.n_reasons = n_reasons
        self.llm_generation_counter = 0

    def get_next_seed(self):
        """
        Returns a unique deterministic seed for each LLM generation.
        """

        seed = self.seed + self.llm_generation_counter
        self.llm_generation_counter += 1

        return seed

    def evaluate_prompt(self, prompt, task_type, max_examples=None):
        """
        Evaluates a prompt on the optimization dataset.

        This function applies the specified prompt to the dataset, evaluates model
        performance, and caches the resulting score to avoid redundant evaluations.

        Args:
            prompt (PromptObject): Prompt to evaluate.
            task_type (str): Task identifier.
            max_examples (int, optional): Number of examples to evaluate.

        Returns:
            dict: Dictionary containing:
                  - 'score': Overall evaluation score.
                  - 'summary': Aggregated evaluation results.
                  - 'details': Per-example evaluation results.
        """

        # Check cache.
        cache_key = (
            task_type,
            self.normalize_prompt(prompt),
            max_examples or self.max_examples,
            self.seed,
        )
        if cache_key in self.cache:
            return self.cache[cache_key]

        # Extract max examples from dataset.
        base = self.dataset[: max_examples or self.max_examples]

        # Generate full prompt.
        data = apply_prompt(base, prompt, task_type)

        # Evaluate prompt.
        summary, details = self.evaluator(
            self.model,
            data,
            max_examples=max_examples or self.max_examples,
            judge_model=self.judge_model,
            return_details=True,
            seed=self.seed,
        )

        # Add raw inputs to results.
        for d, raw_ex in zip(details, base):

            if task_type == "sentiment":

                d["raw_input"] = raw_ex["text"]

            elif task_type == "logical":

                d["raw_input"] = f"""
                Context:
                {raw_ex["context"]}

                Choices:
                {raw_ex["choices"]}

                Question:
                {raw_ex["question"]}
                """

        result = {
            "optimization_score": summary["score"],
            "summary": summary,
            "details": details,
        }

        print("CHILD SCORE:", result["optimization_score"])

        # Cache results.
        self.cache[cache_key] = result

        return result

    def collect_failures(self, details):
        """
        Extracts incorrectly solved examples from evaluation results.

        This function identifies failed predictions and returns a subset that can later
        be analyzed to guide prompt mutations.

        Args:
            details (list): Per-example evaluation results.
            max_failures (int, optional): Maximum number of failures to return.

        Returns:
            list: List of failure records containing inputs, predictions, and expected
                outputs.
        """

        # Extract failure cases.
        failures = [
            {"input": d["raw_input"], "prediction": d["pred"], "truth": d["truth"]}
            for d in details
            if d["score"] == 0 or d["exact"] == 0
        ]

        # Only max failures cases.
        if len(failures) <= self.max_failures:
            return failures

        return self.rng.sample(failures, self.max_failures)

    def analyze_failures(self, failures, prompt, task_type):
        """
        Generates a analysis of prompt weaknesses.

        This function presents failed examples to the mutation model and requests a set
        of general reasons that may explain the observed errors.

        Args:
            failures (list): Collection of failed examples.
            prompt (str): Current prompt being analyzed.
            n_reasons (int, optional): Number of weaknesses to identify.

        Returns:
            str: Failure analysis generated by the mutation model.
        """

        # Generate failure/error cases instances.
        failures_text = "\n".join([f"""
        ## FAILURE CASE {i + 1}

        MODEL INPUT: {f["input"]}
        MODEL OUTPUT: {f["prediction"]}
        TARGET OUTPUT: {f["truth"]}
        """ for i, f in enumerate(failures)])

        # Prompt for failure analysis.
        analysis_prompt = f"""
        I'm trying to write a prompt for a task.

        # CURRENT PROMPT:
        {prompt}

        {self.output_constraints}

        # FAILURE CASES:
        {failures_text}
        
        #
        Analyze the FAILURE CASES and identify recurring, generalizable
        FAILURE PATTERNS in the model's problem-solving behavior.

        You may refer to the structure of individual FAILURE CASES as evidence.
        DO NOT simply memorize individual FAILURE CASES or their answers.

        Identify ONLY GENERALIZABLE FAILURE PATTERNS that are supported by
        multiple FAILURE CASES or by a clearly diagnostic FAILURE CASE.

        LIST up to {self.n_reasons} FAILURE PATTERNS.
        If less than {self.n_reasons} FAILURE PATTERNS are identified, list less.

        For each pattern:
        1. Identify the observed recurring FAILURE PATTERN.
        2. State the evidence in the FAILURE CASES supporting it.
        3. State what aspect of the CURRENT PROMPT may be insufficient to prevent
           or address the FAILURE PATTERN.
        
        Return ONLY the requested analysis.
        DO NOT include other text.
        """

        # Generate LLM failure analysis.
        out = self.mutation_model.generate(
            prompt=analysis_prompt,
            system="You are an helpful assistant.",
            temperature=0.3,
            max_new_tokens=500,
            seed=self.get_next_seed(),
        )

        # Save the optimizer prompt.
        self.optimizer_prompt_log.append(
            {
                "gen": self.current_gen,
                "stage": "failure_analysis",
                "branch": "failure_analysis",
                "target_field": None,
                "optimization_prompt": analysis_prompt,
                "optimizer_output": out,
            }
        )

        return out.strip()

    def render_parent_prompt(self, parent_prompt):
        """
        Renders either a single parent prompt or two crossover parent prompts into
        a single string.
        """
        if parent_prompt is None:
            return None

        if isinstance(parent_prompt, tuple):
            parent_a, parent_b = parent_prompt

            return (
                "PARENT A:\n"
                f"{parent_a.render()}\n\n"
                "PARENT B:\n"
                f"{parent_b.render()}"
            )

        return parent_prompt.render()

    def normalize_prompt(self, prompt):
        """
        Generates a normalized identifier for a prompt.

        This function removes formatting differences and computes a stable
        representation that can be used for caching and duplicate detection.

        Args:
            prompt (PromptObject): Prompt to normalize.

        Returns:
            str: MD5 hash of the normalized prompt.
        """
        s = prompt.render().lower()
        s = re.sub(r"\s+", " ", s).strip()
        return hashlib.md5(s.encode()).hexdigest()

    def serialize_prompt_object(self, prompt):
        """
        Converts a prompt object into a serialized text representation.

        This function combines the instruction, reasoning, examples, and output
        constraints into a structured format.

        Args:
            prompt (PromptObject): Prompt to serialize.

        Returns:
            str: Serialized prompt representation.
        """
        # Check if prompt object is raw prompt.
        if prompt.raw_prompt.strip():
            return prompt.raw_prompt

        # Init examples string.
        examples_str = "\n\n".join(prompt.examples or [])

        # Construct prompt dissection.
        return f"""
        INSTRUCTION:
        {prompt.instruction}

        REASONING:
        {prompt.reasoning}

        EXAMPLES:
        {examples_str}

        OUTPUT CONSTRAINTS:
        {self.output_constraints}
        """

    def split_examples(self, text):
        """
        Extracts individual examples from generated example text.

        This function parses LLM generated demonstrations and separates them into
        individual examples suitable for storage within a PromptObject.

        Args:
            text (str): Raw generated examples text.

        Returns:
            list: Parsed examples.
        """
        if not text:
            return []

        parts = re.split(r"(?=Example\s+\d+\s*:)", text, flags=re.IGNORECASE)
        cleaned = [p.strip() for p in parts if p.strip()]
        return cleaned

    def build_mutation_prompts(self, prompt, failure_analysis, task_type, max_shots=10):
        """
        Constructs mutation instructions for prompt optimization.

        This function generates mutation prompts targeting specific prompt components
        such as instructions, reasoning steps, examples, or complete prompt rewrites.

        Args:
            prompt (PromptObject): Parent prompt to mutate.
            failure_analysis (str): Analysis describing observed prompt weaknesses.
            task_type (str): Task identifier.
            max_shots (int, optional): Maximum number of examples allowed in the prompt.

        Returns:
            list: Mutation results.
        """
        mutations = []

        # Dissect prompt.
        full_prompt_context = self.serialize_prompt_object(prompt)

        # Extract random sample.
        example_seed = self.rng.choice(self.dataset)

        # Task reference.
        if task_type == "sentiment":

            reference_block = """
            Task:
            Binary sentiment classification of tweets.

            Goal:
            Identify if the sentiment is positive or negative.
            """

        elif task_type == "logical":

            reference_block = """
            Task:
            Logical deduction problem solving involving ordering, position, ranking, 
            spatial relationships, and constraint satisfaction.

            Goal:
            Identify the correct answer among the provided options.
            """

        # Instruction optimization branch.
        if "instruction" in self.branches:
            m = f"""
            You are optimizing ONLY the current prompt INSTRUCTION field.

            # CURRENT PROMPT:
            {full_prompt_context}
            
            # FAILURE ANALYSIS (NOT PART OF THE PROMPT):
            {failure_analysis}
            
            # TASK EXPLANATION (NOT PART OF THE PROMPT): 
            {reference_block}
            
            #
            Do NOT rewrite or return REASONING. 
            Do NOT rewrite or return EXAMPLES.
            Do NOT rewrite or return OUTPUT CONSTRAINTS.

            IMPROVE ONLY the INSTRUCTION with the goal of addressing the failure 
            patterns identified by the FAILURE ANALYSIS. 
            Preserve effective parts of the existing INSTRUCTION.
            Prioritize improving performance on unseen instances over making the prompt
            substantially different.
            The INSTRUCTION must NOT describe a step-by-step solving procedure.
            The INSTRUCTION may specify goals, priorities, constraints, or cautions.
            The INSTRUCTION must be applicable to ALL task instances.

            Return ONLY the rewritten INSTRUCTION. 
            DO NOT include other text.
            DO NOT explain your reasoning.
            """

            mutations.append(("instruction", "instruction", m))

        # Reasoning optimization branch.
        if "cot" in self.branches:

            current_reasoning = prompt.reasoning

            # If reasoning already present improve it.
            if current_reasoning.strip():

                instruction = """
                IMPROVE the REASONING steps to address the failure patterns identified
                by the FAILURE ANALYSIS.
                Do NOT add duplicated REASONING steps.
                Each REASONING step must be an actionable rule for solving the task.
                The IMPROVED REASONING must be a procedure that can be applied to ALL
                task instances.

                Return ONLY the IMPROVED REASONING steps. 
                DO NOT include other text.
                DO NOT explain your reasoning.
                """

            # If reasoning not present add it.
            else:

                instruction = """
                WRITE step-by-step REASONING for the prompt. 
                The REASONING must be a procedure that can be applied to ALL task 
                instances and should help in addressing the failure patterns identified 
                by the FAILURE ANALYSIS.
                Each REASONING step must be an actionable rule for solving the task.

                Return ONLY the REASONING steps. 
                DO NOT include other text.
                DO NOT explain your reasoning.
                """

            m = f"""
            You are optimizing ONLY the current prompt REASONING field. 
            
            # CURRENT PROMPT: 
            {full_prompt_context} 
            
            # FAILURE ANALYSIS (NOT PART OF THE PROMPT):
            {failure_analysis}

            # TASK EXPLANATION (NOT PART OF THE CURRENT PROMPT):
            {reference_block}

            #
            Do NOT rewrite or return INSTRUCTION. 
            Do NOT rewrite or return EXAMPLES. 
            Do NOT rewrite or return OUTPUT CONSTRAINTS.

            {instruction} 
            """

            mutations.append(("cot", "reasoning", m))

        # Examples optimization branch.
        if "examples" in self.branches:

            # Reference example.
            if task_type == "sentiment":

                reference_block = f"""
                {example_seed["text"]}
                Answer: {example_seed["output"]}
                """.strip()

            elif task_type == "logical":

                reference_block = f"""
                {example_seed["context"]}
                {example_seed["question"]}
                Choices:{", ".join(example_seed["choices"])}
                Answer: {example_seed["output"]}
                """.strip()

            # Add examples only until a certain number then improve them.
            if len(prompt.examples) >= max_shots:

                instruction = f"""
                IMPROVE the existing CURRENT PROMPT EXAMPLES usefulness as demonstrations
                to better address the failure patterns identified by the FAILURE ANALYSIS.
                The generated EXAMPLES must be internally CONSISTENT and must have
                exactly ONE correct answer.
                Each EXAMPLE must be representative of the task and generalize to unseen 
                instances.
                Every EXAMPLE in the final result must be distinct from every other EXAMPLE.
                Do NOT produce an EXAMPLE that tests the same underlying problem, reasoning 
                pattern, or answer structure as another EXAMPLE.

                The FAILURE CASES potentially mentioned by the FAILURE ANALYSIS are
                evidence only. Do NOT copy, reproduce, or minimally modify them into
                EXAMPLES.

                Do NOT add any additional EXAMPLES just change or improve the existing ones.
                The final result MUST contain exactly {len(prompt.examples)} EXAMPLES.

                Return ONLY the IMPROVED EXAMPLES. 
                DO NOT include other text.
                DO NOT explain your reasoning.
                """

            else:

                instruction = f"""
                ADD 2 new high-quality EXAMPLES coherent with the task specifically 
                designed to address the failure patterns identified by the FAILURE ANALYSIS.
                The generated EXAMPLES must be internally CONSISTENT and must have
                exactly ONE correct answer.
                Each EXAMPLE must be representative of the task and generalize to
                unseen instances.
                Every EXAMPLE in the final result must be distinct from every other EXAMPLE.
                Do NOT copy an existing EXAMPLE.
                Do NOT produce an EXAMPLE that tests the same underlying problem, reasoning 
                pattern, or answer structure as another EXAMPLE.

                The FAILURE CASES potentially mentioned by the FAILURE ANALYSIS are
                evidence only. Do NOT copy, reproduce, or minimally modify them into
                EXAMPLES.

                DO NOT include other text.
                DO NOT explain your reasoning.
                Return ONLY the new EXAMPLES in this format:

                Example {len(prompt.examples) + 1}: 
                ... 
                Answer: ... 
                
                Example {len(prompt.examples) + 2}: 
                ... 
                Answer: ...
                """

            m = f"""
            You are optimizing ONLY the current prompt EXAMPLES field.

            # CURRENT PROMPT:
            {full_prompt_context}

            # FAILURE ANALYSIS (NOT PART OF THE PROMPT):
            {failure_analysis}

            # TASK DEMO REFERENCE (NOT PART OF THE PROMPT):

            {reference_block}
            
            #
            Do NOT rewrite or return INSTRUCTION. 
            Do NOT rewrite or return REASONING. 
            Do NOT rewrite or return OUTPUT CONSTRAINTS. 
            {instruction}
            """

            mutations.append(("examples", "examples", m))

        # Full prompt optimization/rewrite branch.
        if self.branches == ("rewrite",):

            rendered_prompt = prompt.render()

            m = f"""
            You are optimizing the CURRENT PROMPT field.

            # CURRENT PROMPT:
            {rendered_prompt}

            # FAILURE ANALYSIS (NOT PART OF THE PROMPT):
            {failure_analysis}

            # TASK EXPLANATION (NOT PART OF THE PROMPT):
            {reference_block} 
                        
            #
            DO NOT rewrite or return FAILURE ANALYSIS. 
            DO NOT rewrite or return TASK EXPLANATION.

            IMPROVE only the CURRENT PROMPT to maximize performance and to address the 
            failure patterns identified by the FAILURE ANALYSIS.
            Preserve useful parts of the CURRENT PROMPT.
            DO NOT add changes that are unsupported by the FAILURE ANALYSIS.
            The resulting PROMPT must generalize to unseen instances.
    
            Return ONLY the improved PROMPT.
            DO NOT include other text.
            DO NOT explain your reasoning.
            """

            mutations.append(("rewrite", "rewrite", m))

        return mutations

    def mutate(self, node, task_type):
        """
        Generates child prompts from an existing prompt node.

        This function analyzes failures associated with a prompt, constructs mutation
        requests, generates candidate prompt results, and returns the resulting child
        prompts.

        Args:
            node (dict): Prompt node selected for mutation.
            task_type (str): Task identifier.

        Returns:
            list: Collection of generated child prompt nodes.
        """
        seen = set()
        children = []

        # Extract failure cases.
        failures = self.collect_failures(node["details"])

        if not failures:
            return []

        # Generate failure cases analysis.
        failure_analysis = self.analyze_failures(
            failures, node["prompt"].render(), task_type
        )

        # Set max number of examples.
        max_shots = 10 if task_type == "sentiment" else 5

        # Generate branches prompts for mutations.
        mutation_prompts = self.build_mutation_prompts(
            node["prompt"], failure_analysis, task_type, max_shots
        )

        for branch_name, target_field, mutation_prompt in mutation_prompts:

            print("\nMUTATION BRANCH")
            print("BRANCH:", branch_name)

            # Generate LLM mutations.
            out = self.mutation_model.generate(
                prompt=mutation_prompt,
                system=self.optimizer_system,
                max_new_tokens=700,
                temperature=0.6,
                seed=self.get_next_seed(),
            ).strip()

            # Save the optimization prompt and model output.
            self.optimizer_prompt_log.append(
                {
                    "gen": self.current_gen,
                    "stage": "mutation",
                    "branch": branch_name,
                    "target_field": target_field,
                    "optimization_prompt": mutation_prompt,
                    "optimizer_output": out,
                }
            )

            if not out:
                continue

            new_prompt = deepcopy(node["prompt"])
            new_prompt.examples = list(new_prompt.examples)

            # Construct mutated prompts based on branch type.
            if target_field == "rewrite":

                new_prompt.raw_prompt = out

                new_prompt.instruction = ""
                new_prompt.reasoning = ""
                new_prompt.examples = []

            elif target_field == "instruction":

                new_prompt.instruction = out

            elif target_field == "reasoning":

                new_prompt.reasoning = out

            elif target_field == "examples":

                # Split examples string.
                parsed = self.split_examples(out)

                if not parsed:
                    continue

                if len(new_prompt.examples) >= max_shots:
                    new_prompt.examples = parsed[:max_shots]

                else:

                    # Clean examples.
                    def normalize(s):
                        return re.sub(r"\s+", " ", s.strip().lower())

                    existing = set(normalize(e) for e in new_prompt.examples)

                    # Add new generated examples.
                    for ex in parsed:
                        if normalize(ex) not in existing:
                            new_prompt.examples.append(ex)
                            existing.add(normalize(ex))

                    # Hard cap.
                    new_prompt.examples = new_prompt.examples[:max_shots]

            # Render new mutated prompt.
            rendered = new_prompt.render()

            if rendered in seen:
                continue

            seen.add(rendered)

            children.append(
                {
                    "prompt": new_prompt,
                    "parent_prompt": node["prompt"],
                    "mutation_type": branch_name,
                    "birth_gen": self.current_gen,
                }
            )

        return children

    def initialize_population(self, initial_prompts, task_type):
        """
        Initializes the top-k population by generating mutations from the initial prompt.

        The initial prompt is always retained as a candidate. Additional candidates are
        generated through a mutation chain. The k highest-scoring unique prompts form the
        initial optimization pool.
        """
        if isinstance(initial_prompts, PromptObject):
            initial_prompts = [initial_prompts]

        candidates = []
        initial_nodes = []

        # Evaluate initial prompts.
        for p in initial_prompts:
            result = self.evaluate_prompt(
                p,
                task_type,
                max_examples=self.max_examples,
            )

            node = {
                "prompt": p,
                "optimization_score": result["optimization_score"],
                "summary": result["summary"],
                "details": result["details"],
                "parent_prompt": None,
                "mutation_type": None,
                "birth_gen": -1,
            }

            initial_nodes.append(node)
            candidates.append(node)

        # Generate mutation chains.
        for initial_node in candidates.copy():

            current_parent = initial_node

            while len(candidates) < self.k:

                self.current_gen = 0

                children = self.mutate(current_parent, task_type)

                if not children:
                    break

                evaluated_children = []

                # Evaluate every branch generated from this parent.
                for child in children:

                    result = self.evaluate_prompt(
                        child["prompt"], task_type, max_examples=self.max_examples
                    )

                    child_node = {
                        **child,
                        "optimization_score": result["optimization_score"],
                        "summary": result["summary"],
                        "details": result["details"],
                    }

                    evaluated_children.append(child_node)
                    candidates.append(child_node)

                    self.mutation_log.append(
                        {
                            "init_prompt": self.current_init_prompt,
                            "gen": 0,
                            "branch": child["mutation_type"],
                            "parent_prompt": self.render_parent_prompt(
                                child["parent_prompt"]
                            ),
                            "parent_score": current_parent["optimization_score"],
                            "child_prompt": child["prompt"].render(),
                            "child_score": result["optimization_score"],
                        }
                    )

                # Continue the initialization chain from the best child
                # generated at this depth.
                current_parent = max(
                    evaluated_children, key=lambda x: x["optimization_score"]
                )

        # Remove duplicate prompts.
        dedup = {}

        for node in candidates:

            key = self.normalize_prompt(node["prompt"])

            if key not in dedup:
                dedup[key] = node

            elif node["optimization_score"] > dedup[key]["optimization_score"]:
                dedup[key] = node

        candidates = list(dedup.values())

        # Keep the k best prompts.
        candidates.sort(
            key=lambda x: (x["optimization_score"], x.get("birth_gen", -1)),
            reverse=True,
        )

        self.pool = candidates[: self.k]

        return initial_nodes

    def crossover(self, parent_a, parent_b):
        """
        Creates a new structured prompt by independently selecting prompt components
        from two parent prompts.

        Crossover is only applicable to structured PromptObjects.
        """
        if parent_a.raw_prompt.strip() or parent_b.raw_prompt.strip():
            return None

        child = deepcopy(parent_a)

        # Instruction crossover.
        child.instruction = self.rng.choice(
            [parent_a.instruction, parent_b.instruction]
        )

        # Reasoning crossover.
        child.reasoning = self.rng.choice([parent_a.reasoning, parent_b.reasoning])

        # Examples crossover.
        child.examples = list(self.rng.choice([parent_a.examples, parent_b.examples]))

        rendered = child.render()

        if rendered in {parent_a.render(), parent_b.render()}:
            return None

        return {
            "prompt": child,
            "parent_prompt": (parent_a, parent_b),
            "mutation_type": "crossover",
            "birth_gen": self.current_gen,
        }

    def optimize(self, initial_prompts, task_type, generations=20):
        """
        Executes the prompt optimization process.

        This function repeatedly selects prompts from the optimization pool, generates
        mutations, evaluates candidate prompts, and updates the pool using a top-k
        selection strategy. Optimization continues until the maximum number of
        generations is reached or early stopping is triggered.

        Args:
            initial_prompts: Initial prompt or collection of prompts.
            task_type (str): Task identifier.
            generations (int, optional): Maximum number of optimization generations.

        Returns:
            tuple: Contains:
                   - Optimization history across generations.
                   - Mutation log recording generated prompt variants.
        """
        # Clean pool, cache, logs.
        self.pool = []
        self.cache = {}
        self.mutation_log = []
        self.optimizer_prompt_log = []
        self.llm_generation_counter = 0

        # Initialize the beam with the baseline prompt and its
        # first-generation mutations.
        initial_nodes = self.initialize_population(
            initial_prompts,
            task_type,
        )

        # The current experiment passes one initial PromptObject.
        initial_node = initial_nodes[0]

        # Init patience stalling and best score.
        best_score_seen = self.pool[0]["optimization_score"]
        stall_generations = 0

        # Initialize history with the original prompt as generation 0.
        history = [
            {
                "gen": 0,
                "prompt": initial_node["prompt"],
                "optimization_score": initial_node["optimization_score"],
                "improvement": 0.0,
                "parent_prompt": None,
                "mutation_type": None,
                "summary": initial_node["summary"],
                "details": initial_node["details"],
            }
        ]

        for g in tqdm(range(1, generations + 1), desc="Optimizing"):

            self.current_gen = g

            if not self.pool:
                return history

            selection_pool = self.pool[: self.k]

            """# Higher-ranked prompts receive higher probability.
            weights = list(range(len(selection_pool), 0, -1))

            seed = self.rng.choices(selection_pool, weights=weights, k=1)[0]"""

            seed = self.rng.choice(selection_pool)

            # Mutate prompt.
            children = self.mutate(seed, task_type)

            # Add crossover for the combined branches optimizer.
            if (
                set(self.branches) == {"instruction", "cot", "examples"}
                and len(self.pool) >= 2
            ):
                parent_a, parent_b = self.rng.sample(self.pool, 2)

                cross_child = self.crossover(parent_a["prompt"], parent_b["prompt"])

                if cross_child is not None:
                    cross_child["parent_score"] = (
                        parent_a["optimization_score"],
                        parent_b["optimization_score"],
                    )
                    children.append(cross_child)

            if not children:
                continue

            for child in children:

                # Evaluate children prompt.
                result = self.evaluate_prompt(
                    child["prompt"], task_type, max_examples=self.max_examples
                )

                if child["mutation_type"] == "crossover":
                    parent_score = child["parent_score"]
                else:
                    parent_score = seed["optimization_score"]

                # Append children prompt data to the log.
                self.mutation_log.append(
                    {
                        "init_prompt": self.current_init_prompt,
                        "gen": g,
                        "branch": child["mutation_type"],
                        "parent_prompt": self.render_parent_prompt(
                            child["parent_prompt"]
                        ),
                        "parent_score": parent_score,
                        "child_prompt": child["prompt"].render(),
                        "child_score": result["optimization_score"],
                    }
                )

                # Store children prompt evaluation results.
                child_node = {
                    **child,
                    "optimization_score": result["optimization_score"],
                    "summary": result["summary"],
                    "details": result["details"],
                }

                # Add children prompt evaluation results to the pool.
                self.pool.append(child_node)

            dedup = {}

            for n in self.pool:

                key = self.normalize_prompt(n["prompt"])

                if key not in dedup:
                    dedup[key] = n

                else:
                    if n["optimization_score"] > dedup[key]["optimization_score"] or (
                        n["optimization_score"] == dedup[key]["optimization_score"]
                        and n.get("birth_gen", -1) > dedup[key].get("birth_gen", -1)
                    ):
                        dedup[key] = n

            self.pool = list(dedup.values())

            # Sort prompts pool by score (on ties newest wins).
            self.pool.sort(
                key=lambda x: (x["optimization_score"], x.get("birth_gen", -1)),
                reverse=True,
            )

            # Keep only top k performing prompts in pool.
            self.pool = self.pool[: self.k]

            # Extract best performing prompt.
            best = self.pool[0]

            # Update patience stalling.
            if best["optimization_score"] > best_score_seen:
                best_score_seen = best["optimization_score"]
                stall_generations = 0
            else:
                stall_generations += 1

            prev = history[-1]["optimization_score"] if len(history) > 1 else None

            print("GEN:", g)
            print("BEST SCORE:", best["optimization_score"])
            print("POOL SCORES:")
            for p in self.pool:
                print(p["optimization_score"])

            # Append best performing prompt results and data to mutation history.
            history.append(
                {
                    "gen": g,
                    "prompt": best["prompt"],
                    "optimization_score": best["optimization_score"],
                    "improvement": (
                        best["optimization_score"] - prev if prev is not None else 0.0
                    ),
                    "parent_prompt": best["parent_prompt"],
                    "mutation_type": best["mutation_type"],
                    "summary": best["summary"],
                    "details": best["details"],
                }
            )

            # Stop if max number of patience stalling generations has been reached.
            if stall_generations >= self.patience:

                print(
                    f"\nEARLY STOPPING: no improvement for {self.patience} generations.\n"
                )

                break

        return history, self.mutation_log
